package com.example.payment;

/**
 * 支付状态枚举
 * 定义支付记录在支付流程中可能出现的各种状态
 */
public enum PaymentStatus {

    /**
     * 待支付状态
     * 支付订单已创建，等待用户完成支付操作
     */
    PENDING,

    /**
     * 支付成功状态
     * 用户已成功完成支付，款项已到账
     */
    SUCCESS,

    /**
     * 支付失败状态
     * 支付过程中出现错误（如余额不足、网络异常等）导致支付失败
     */
    FAILED,

    /**
     * 已关闭状态
     * 支付订单超时未支付或被主动关闭，无法继续支付
     */
    CLOSED,

    /**
     * 已退款状态
     * 支付成功后，因业务原因（如取消挂号）已完成退款
     */
    REFUNDED
}